using DeliverySystem.Domain;
using DeliverySystem.Extensions;
using DeliverySystem.Functional;
using DeliverySystem.IO;
using DeliverySystem.Native;
using DeliverySystem.Processing;
using DeliverySystem.Reports;
using DeliverySystem.Services;
var path=Path.Combine(AppContext.BaseDirectory,"deliveries.json");
var loaded=DeliveryFileStore.Load(path);
if(loaded is Result<List<DeliveryInput>,DomainError>.Failure fail){Console.WriteLine($"{fail.Error.Code}: {fail.Error.Message}");return;}
var inputs=((Result<List<DeliveryInput>,DomainError>.Success)loaded).Value;
var requests=inputs.Select(DeliveryValidator.Validate).OfType<Result<DeliveryRequest,DomainError>.Success>().Select(x=>x.Value).ToArray();
Console.WriteLine("LONG DISTANCE REPORT");
foreach(var row in DeliveryReports.LongDistance(requests,PricingService.Standard)) Console.WriteLine($"{row.Customer}: {row.DistanceKm} km, {row.EstimatedPrice} KZT");
Console.WriteLine("TOTALS BY CATEGORY");
foreach(var row in DeliveryReports.TotalsByCategory(requests,PricingService.Standard)) Console.WriteLine($"{row.Category}: {row.Count} deliveries, {row.Total} KZT");
var snapshot=DeferredDeliveryProcessor.Snapshot(requests,PricingService.Standard);
Console.WriteLine($"Snapshot contains {snapshot.Length} quotes.");
var native=new NativeFee().Calculate(2000,100);
Console.WriteLine(native is Result<int,DomainError>.Success s ? $"Native surcharge: {s.Value} cents" : "Native call unavailable; build native library using README instructions.");
